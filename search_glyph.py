data = open('kernel.bin','rb').read()
pats = [('V', bytes([0x42,0x42,0x42,0x24,0x24,0x18])),
        ('O', bytes([0x3C,0x42,0x42,0x42,0x42,0x3C])),
        ('R', bytes([0x3C,0x42,0x42,0x3C,0x42,0x42,0x3C])),
        ('T', bytes([0xFE,0x10,0x10,0x10,0x10,0x10,0x10])),
        ('E', bytes([0xFE,0x80,0x80,0xF8,0x80,0x80,0xFE])),
        ('X', bytes([0x82,0x44,0x28,0x10,0x28,0x44,0x82])),
        ('0', bytes([0x3C,0x42,0x42,0x42,0x42,0x42,0x3C]))]
for name, pat in pats:
    idx = data.find(pat)
    print('%s: %s' % (name, ('found at ' + hex(idx)) if idx >= 0 else 'not found'))
pat2 = bytes([0x00, 0xFF])
print('0xFF00 cell pattern count: %d' % data.count(pat2))
